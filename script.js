async function notifyOperators(booking) {
  const webhookUrl = String(state.content.settings.operatorWebhookUrl || "").trim();
  const telegramToken = String(state.content.settings.telegramBotToken || "").trim();
  const telegramChats = String(state.content.settings.telegramChatIds || "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);

  let sent = false;
  let failed = false;

  const payload = {
    bookingId: booking.id,
    traveler: booking.userName,
    phone: booking.phone,
    destination: booking.destinationName,
    people: booking.people,
    totalUsd: booking.totalUsd,
    totalLabel: formatMoney(booking.totalUsd),
    language: booking.language,
    travelDate: booking.travelDate,
    travelDateLabel: booking.travelDateFormatted,
    createdAt: booking.createdAt,
    createdLabel: booking.createdLabel
  };

  if (webhookUrl) {
    try {
      await fetch(webhookUrl, {
        method: "POST",
        mode: "no-cors",
        headers: {
          "Content-Type": "text/plain;charset=utf-8"
        },
        body: JSON.stringify(payload)
      });
      sent = true;
    } catch {
      failed = true;
    }
  }

  if (telegramToken && telegramChats.length) {
    const text = [
      "New booking",
      `Traveler: ${booking.userName}`,
      `Phone: ${booking.phone}`,
      `Destination: ${booking.destinationName}`,
      `People: ${booking.people}`,
      `Travel date: ${booking.travelDateFormatted}`,
      `Total: ${formatMoney(booking.totalUsd)}`
    ].join("\n");

    await Promise.all(telegramChats.map(async (chatId) => {
      try {
        await fetch(`https://api.telegram.org/bot${telegramToken}/sendMessage`, {
          method: "POST",
          mode: "no-cors",
          headers: {
            "Content-Type": "application/json"
          },
          body: JSON.stringify({ chat_id: chatId, text })
        });
        sent = true;
      } catch {
        failed = true;
      }
    }));
  }

  if (sent) {
    return "sent";
  }
  if (failed) {
    return "failed";
  }
  return "pending";
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

